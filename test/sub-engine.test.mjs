test('parseRawLinks and assembleSubscriptionBundle preserve host/sni and warn on Reality', () => {
  const vmessJson = JSON.stringify({
    v: '2',
    ps: 'My-VMess',
    add: 'cdn.example.com',
    port: '443',
    id: '11111111-1111-1111-1111-111111111111',
    aid: '0',
    net: 'ws',
    host: 'ws.example.com',
    path: '/ws',
    tls: 'tls',
    sni: 'ws.example.com',
  });
  const links = [
    `vmess://${b64EncodeUtf8(vmessJson)}`,
    'vless://22222222-2222-2222-2222-222222222222@xhttp.example.com:443?security=tls&type=xhttp&mode=auto&host=xhttp.example.com&sni=xhttp.example.com&path=%2Fxhttp#CF-XHTTP',
    'vless://33333333-3333-3333-3333-333333333333@direct.example.com:443?security=reality&type=tcp#Direct-Reality',
  ].join('\n');

  const { nodes, warnings } = parseRawLinks(links);
  assert.equal(nodes.length, 3);
  assert.ok(warnings.some((w) => w.includes('Reality')));
  assert.ok(warnings.some((w) => w.includes('xhttp')));

  const endpoints = parseCfstCsv(SAMPLE_CSV, { topN: 2, maxLossRate: 0.2, minSpeedMBps: 5 }).selected;
  const bundle = assembleSubscriptionBundle(
    {
      baseLinks: links.split('\n').slice(0, 2).join('\n'),
      customIps: '1.0.0.1:8443#Pinned',
      namePrefix: 'CF',
      includeMetricsInName: true,
      customFirst: true,
    },
    endpoints
  );

  assert.equal(bundle.assembledNodes.length, 6);
  assert.equal(bundle.assembledNodes[0].server, '1.0.0.1');
  assert.equal(bundle.assembledNodes[0].port, 8443);
  assert.equal(bundle.assembledNodes[0].host, 'ws.example.com');
  assert.equal(bundle.assembledNodes[1].server, '104.17.147.26');
  assert.match(bundle.assembledNodes[1].name, /SJC.*45\.8MB\/s/);

  const decodedRaw = b64DecodeUtf8(bundle.rendered.raw).split('\n');
  assert.equal(decodedRaw.length, 6);
  assert.ok(decodedRaw[0].startsWith('vmess://'));
  assert.ok(decodedRaw[4].includes('type=xhttp'));
  assert.ok(bundle.rendered['clash-provider'].startsWith('# Generated by cf-local-sub'));
  assert.ok(bundle.rendered.clash.includes('proxy-groups:'));
  assert.ok(bundle.rendered.surge.includes('= vmess,'));
});

