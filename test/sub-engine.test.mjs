test('HTTP server persists config, imports CSV, renders /sub, and enforces tokens', async (t) => {
  const tmpDir = fs.mkdtempSync(path.join(os.tmpdir(), 'cf-local-sub-test-'));
  const { server, scheduler } = createAppServer({
    dataDir: tmpDir,
    env: {
      ...process.env,
      SUB_ACCESS_TOKEN: 'sub-secret',
      ADMIN_TOKEN: 'admin-secret',
      SCHEDULE_INTERVAL_MINUTES: '0',
    },
  });

  await new Promise((resolve) => server.listen(0, '127.0.0.1', resolve));
  t.after(async () => {
    scheduler.stop();
    await new Promise((resolve) => server.close(resolve));
    fs.rmSync(tmpDir, { recursive: true, force: true });
  });

  const { port } = server.address();
  const baseUrl = `http://127.0.0.1:${port}`;

  const healthRes = await fetch(`${baseUrl}/health`);
  assert.equal(healthRes.status, 200);
  const healthJson = await healthRes.json();
  assert.equal(healthJson.ok, true);

  const unauthApi = await fetch(`${baseUrl}/api/status`);
  assert.equal(unauthApi.status, 401);

  const saveRes = await fetch(`${baseUrl}/api/config`, {
    method: 'POST',
    headers: {
      'content-type': 'application/json',
      'x-admin-token': 'admin-secret',
    },
    body: JSON.stringify({
      config: {
        subscription: {
          baseLinks: 'vless://44444444-4444-4444-4444-444444444444@cdn.example.com:443?security=tls&type=ws&host=cdn.example.com&sni=cdn.example.com&path=%2Fws#CF-WS',
          topN: 2,
          namePrefix: 'LOCAL',
        },
        strategy: {
          enableLocalCfst: true,
          enableDynamicIps: false,
          enableBuiltinDomains: false,
          enableGithubIps: false,
        },
      },
    }),
  });
  assert.equal(saveRes.status, 200);

  const importRes = await fetch(`${baseUrl}/api/import-csv`, {
    method: 'POST',
    headers: {
      'content-type': 'application/json',
      'x-admin-token': 'admin-secret',
    },
    body: JSON.stringify({ csvText: SAMPLE_CSV }),
  });
  assert.equal(importRes.status, 200);
  const importJson = await importRes.json();
  assert.equal(importJson.metrics.selectedIpsCount, 2);
  assert.equal(importJson.metrics.outputNodesCount, 2);

  const unauthSub = await fetch(`${baseUrl}/sub/default?target=clash-provider`);
  assert.equal(unauthSub.status, 403);

  const providerRes = await fetch(`${baseUrl}/sub/default?target=clash-provider&token=sub-secret`);
  assert.equal(providerRes.status, 200);
  const providerYaml = await providerRes.text();
  assert.ok(providerYaml.includes('104.17.147.26'));
  assert.ok(providerYaml.includes('104.29.125.238'));
  assert.ok(providerYaml.includes('Host: "cdn.example.com"'));

  const staticProvider = fs.readFileSync(path.join(tmpDir, 'output', 'sub_provider.yaml'), 'utf8');
  assert.equal(staticProvider, providerYaml);
});

function createMockOnlineFetch(state = { dynamicIp: '172.64.10.1', failDynamic: false, callCount: 0 }) {
  return async (url) => {
    state.callCount += 1;
    const u = String(url);
    if (u.includes('wetest.vip')) {
      if (state.failDynamic) throw new Error('network down');
      return new Response(
        JSON.stringify({
          info: {
            CT: [
              { ip: state.dynamicIp, loss_rate: 5, rtt_avg: 85, speed: 5000, colo: 'SJC' },
              { ip: '172.64.10.99', loss_rate: 35, rtt_avg: 90, speed: 3000, colo: 'LAX' },
            ],
          },
        }),
        { status: 200 }
      );
    }
    if (u.includes('hostmonit.com')) {
      if (state.failDynamic) throw new Error('network down');
      return new Response(
        JSON.stringify({
          info: [
            { ip: '104.21.10.2', line: 'CU', latency: 92, speed: 4200, loss: 0 },
            { ip: '104.21.10.99', line: 'CM', latency: 95, speed: 4000, loss: 25 },
          ],
        }),
        { status: 200 }
      );
    }
    if (u.includes('xingpingcn')) {
      if (state.failDynamic) throw new Error('network down');
      return new Response(
        JSON.stringify({ Cf: { result: { dianxin: ['104.22.10.3'], default: ['104.22.10.4'] } } }),
        { status: 200 }
      );
    }
    if (u.includes('ipdb.api') || u.includes('bestcfv4.txt')) {
      if (state.failDynamic) return new Response('err', { status: 502 });
      return new Response('104.23.10.5#CN\n172.64.10.1#dup\n', { status: 200 });
    }
    if (u.includes('LancelotRar')) {
      return new Response('104.24.10.6:8443#US 8.5MB/s\n104.24.10.99#0.00MB/s\n', { status: 200 });
    }
    if (u.includes('gslege')) {
      return new Response('104.25.10.7#JP\n', { status: 200 });
    }
    if (u.includes('ymyuuu/IPDB')) {
      return new Response('104.26.10.8#HK\n', { status: 200 });
    }
    return new Response('not found', { status: 404 });
  };
}

test('OnlineSourceManager aggregates 18 domains, 4 dynamic, 3 github routes with TTL cache and disk fallback', async (t) => {
  assert.equal(BUILTIN_DOMAINS.length, 18);
  assert.equal(getBuiltinDomainItems().length, 18);

  const tmpDir = fs.mkdtempSync(path.join(os.tmpdir(), 'cf-online-pool-test-'));
  t.after(() => fs.rmSync(tmpDir, { recursive: true, force: true }));

  const mockState = { dynamicIp: '172.64.10.1', failDynamic: false, callCount: 0 };
  const manager = new OnlineSourceManager(tmpDir, {
    fetchImpl: createMockOnlineFetch(mockState),
  });

  const firstPool = await manager.getPool({ sourceCacheTtlSec: 300 });
  assert.equal(firstPool.cacheState.mode, 'live');
  assert.equal(firstPool.domainItems.length, 18);
  assert.equal(firstPool.dynamicItems.length, 5); // 5 valid, 2 loss>20 dropped, 1 dup dropped
  assert.equal(firstPool.githubItems.length, 3); // 0.00MB/s line skipped
  assert.ok(firstPool.dynamicItems.some((i) => i.server === '172.64.10.1'));
  assert.ok(!firstPool.dynamicItems.some((i) => i.server === '172.64.10.99'));
  assert.ok(!firstPool.githubItems.some((i) => i.server === '104.24.10.99'));

  const countAfterFirst = mockState.callCount;
  const cachedPool = await manager.getPool({ sourceCacheTtlSec: 300 });
  assert.equal(cachedPool.cacheState.mode, 'memory');
  assert.equal(mockState.callCount, countAfterFirst);

  // Simulate upstream dynamic failure after forced refresh -> per-source disk snapshot fallback
  mockState.failDynamic = true;
  const fallbackPool = await manager.getPool({ forceRefresh: true, sourceCacheTtlSec: 300, enableDiskPoolFallback: true });
  assert.equal(fallbackPool.cacheState.mode, 'forced-live');
  assert.equal(fallbackPool.dynamicItems.length, 5);
  const wetestStatus = fallbackPool.sourceStatus.find((s) => s.key === 'wetest');
  assert.equal(wetestStatus.ok, true);
  assert.equal(wetestStatus.stale, true);

  // Test priority ordering and selectOnlineEndpoints slicing
  assert.deepEqual(selectOnlineEndpoints(fallbackPool, {}), []);
  const sliced = selectOnlineEndpoints(fallbackPool, {
    enableBuiltinDomains: false,
    enableDynamicIps: true,
    maxDynamic: 2,
    enableGithubIps: true,
    maxGithub: 1,
  });
  assert.equal(sliced.length, 3);

  const localEp = [{ server: '104.17.147.26', source: 'cfst', remark: 'SJC' }];
  const mergedDefault = resolvePreferredEndpoints(
    localEp,
    { customIps: '1.0.0.1#Custom' },
    sliced
  );
  assert.equal(mergedDefault[0].server, '104.17.147.26');
  assert.equal(mergedDefault[1].server, '1.0.0.1');
  assert.equal(mergedDefault[2].server, '172.64.10.1');

  const mergedLocalFirst = resolvePreferredEndpoints(
    localEp,
    { customIps: '1.0.0.1#Custom', endpointPriority: 'local-custom-online' },
    sliced
  );
  assert.equal(mergedLocalFirst[0].server, '104.17.147.26');
  assert.equal(mergedLocalFirst[1].server, '1.0.0.1');

  const mergedOnlineFirst = resolvePreferredEndpoints(
    localEp,
    { customIps: '1.0.0.1#Custom', endpointPriority: 'online-local-custom' },
    sliced
  );
  assert.equal(mergedOnlineFirst[0].server, '172.64.10.1');
});

test('HTTP server /api/generate, /api/online-sources, and /sub?refresh=1 combine Worker + local CFST', async (t) => {
  const tmpDir = fs.mkdtempSync(path.join(os.tmpdir(), 'cf-hybrid-http-test-'));
  const mockState = { dynamicIp: '172.64.10.1', failDynamic: false, callCount: 0 };
  const { server, scheduler } = createAppServer({
    dataDir: tmpDir,
    fetchImpl: createMockOnlineFetch(mockState),
    env: {
      ...process.env,
      SCHEDULE_INTERVAL_MINUTES: '0',
    },
  });

  await new Promise((resolve) => server.listen(0, '127.0.0.1', resolve));
  t.after(async () => {
    scheduler.stop();
    await new Promise((resolve) => server.close(resolve));
    fs.rmSync(tmpDir, { recursive: true, force: true });
  });

  const { port } = server.address();
  const baseUrl = `http://127.0.0.1:${port}`;

  // Import local CSV first
  const importRes = await fetch(`${baseUrl}/api/import-csv`, {
    method: 'POST',
    headers: { 'content-type': 'application/json' },
    body: JSON.stringify({ csvText: SAMPLE_CSV }),
  });
  assert.equal(importRes.status, 200);

  // Default strategy generates local CFST only without hitting online sources
  const localOnlyRes = await fetch(`${baseUrl}/api/generate`, {
    method: 'POST',
    headers: { 'content-type': 'application/json' },
    body: JSON.stringify({
      config: {
        subscription: {
          baseLinks: 'vless://55555555-5555-5555-5555-555555555555@cdn.example.com:443?security=tls&type=ws&host=cdn.example.com&sni=cdn.example.com&path=%2Fws#CF-Demo',
          topN: 2,
        },
      },
    }),
  });
  assert.equal(localOnlyRes.status, 200);
  const localOnlyJson = await localOnlyRes.json();
  assert.equal(localOnlyJson.config.subscription.endpointPriority, 'local-custom-online');
  assert.equal(localOnlyJson.endpointBreakdown.cfst, 2);
  assert.equal(localOnlyJson.endpointBreakdown.dynamic, 0);
  assert.equal(localOnlyJson.endpointBreakdown.builtin, 0);
  assert.equal(localOnlyJson.endpointBreakdown.github, 0);
  assert.equal(localOnlyJson.metrics.outputNodesCount, 2);
  assert.equal(mockState.callCount, 0);

  // Generate subscription combining base link + local CFST (2) + 18 builtin + 5 dynamic + 1 custom
  const genRes = await fetch(`${baseUrl}/api/generate`, {
    method: 'POST',
    headers: { 'content-type': 'application/json' },
    body: JSON.stringify({
      config: {
        subscription: {
          baseLinks: 'vless://55555555-5555-5555-5555-555555555555@cdn.example.com:443?security=tls&type=ws&host=cdn.example.com&sni=cdn.example.com&path=%2Fws#CF-Demo',
          customIps: '1.1.1.1:8443#Pinned',
          topN: 2,
          endpointPriority: 'custom-local-online',
        },
        strategy: {
          enableLocalCfst: true,
          enableDynamicIps: true,
          enableBuiltinDomains: true,
          enableGithubIps: false,
          maxDynamic: 40,
          sourceCacheTtlSec: 300,
        },
      },
    }),
  });
  assert.equal(genRes.status, 200);
  const genJson = await genRes.json();
  assert.equal(genJson.endpointBreakdown.custom, 1);
  assert.equal(genJson.endpointBreakdown.cfst, 2);
  assert.equal(genJson.endpointBreakdown.builtin, 18);
  assert.equal(genJson.endpointBreakdown.dynamic, 5);
  assert.equal(genJson.metrics.outputNodesCount, 26);

  const detailsRes = await fetch(`${baseUrl}/api/online-sources`);
  assert.equal(detailsRes.status, 200);
  const detailsJson = await detailsRes.json();
  assert.equal(detailsJson.countsByCategory.domain, 18);
  assert.equal(detailsJson.countsByCategory.dynamic, 5);
  assert.equal(detailsJson.cacheState.mode, 'memory');

  // Mutate upstream mock IP and verify ?refresh=1 bypasses TTL cache on /sub/default
  mockState.dynamicIp = '172.64.10.222';
  const subCached = await (await fetch(`${baseUrl}/sub/default?target=clash-provider`)).text();
  assert.ok(subCached.includes('172.64.10.1'));
  assert.ok(!subCached.includes('172.64.10.222'));

  const subRefreshed = await (await fetch(`${baseUrl}/sub/default?target=clash-provider&refresh=1`)).text();
  assert.ok(subRefreshed.includes('172.64.10.222'));
});
